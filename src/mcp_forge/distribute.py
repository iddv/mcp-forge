"""Generate distribution files: Claude Code plugin, Agent Skill, MCPB bundle, MCP Registry."""

import ast
import json
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional


MCPB_MANIFEST_VERSION = "0.4"
REGISTRY_SCHEMA = "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json"


@dataclass
class ProjectInfo:
    name: str
    description: str
    version: str
    author: str
    github_user: Optional[str]

    @property
    def plugin_name(self) -> str:
        """Kebab-case name, as required for plugins and skills."""
        return re.sub(r"[^a-z0-9]+", "-", self.name.lower()).strip("-")


@dataclass
class ToolInfo:
    name: str
    description: str


def _pyproject_field(text: str, key: str, default: str) -> str:
    match = re.search(rf'^{key}\s*=\s*"([^"]*)"', text, re.MULTILINE)
    return match.group(1) if match else default


def _git(project_dir: Path, *args: str) -> Optional[str]:
    try:
        out = subprocess.run(
            ["git", *args], cwd=project_dir, capture_output=True, text=True, timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0:
        return None
    return out.stdout.strip() or None


def read_project_info(project_dir: Path) -> ProjectInfo:
    pyproject = project_dir / "pyproject.toml"
    text = pyproject.read_text() if pyproject.exists() else ""
    remote = _git(project_dir, "remote", "get-url", "origin") or ""
    github = re.search(r"github\.com[:/]([^/]+)/", remote)
    return ProjectInfo(
        name=_pyproject_field(text, "name", project_dir.name),
        description=_pyproject_field(text, "description", "An MCP server"),
        version=_pyproject_field(text, "version", "0.1.0"),
        author=_git(project_dir, "config", "user.name") or "Your Name",
        github_user=github.group(1) if github else None,
    )


def read_tools(project_dir: Path) -> List[ToolInfo]:
    """Find tools declared with ``@mcp.tool(...)`` / ``@apps.tool(...)`` in server.py."""
    tree = ast.parse((project_dir / "server.py").read_text())
    tools = []
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for dec in node.decorator_list:
            call = dec if isinstance(dec, ast.Call) else None
            func = call.func if call else dec
            if not (isinstance(func, ast.Attribute) and func.attr == "tool"):
                continue
            kwargs = {kw.arg: kw.value for kw in call.keywords} if call else {}
            name = node.name
            if isinstance(kwargs.get("name"), ast.Constant):
                name = kwargs["name"].value
            description = (ast.get_docstring(node) or "").split("\n")[0]
            if isinstance(kwargs.get("description"), ast.Constant):
                description = kwargs["description"].value
            tools.append(ToolInfo(name=name, description=description))
            break
    return tools


def _write_new(path: Path, content: str, created: List[Path]) -> None:
    """Write a file unless it already exists."""
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    created.append(path)


def _json(data: dict) -> str:
    return json.dumps(data, indent=2) + "\n"


def write_skill(project_dir: Path) -> List[Path]:
    """Write skills/<name>/SKILL.md describing when and how to use the server."""
    info = read_project_info(project_dir)
    tools = read_tools(project_dir)
    tool_lines = "\n".join(
        f"- `{tool.name}`" + (f": {tool.description}" if tool.description else "") for tool in tools
    ) or "- (no tools yet)"

    description = (
        f"Use the {info.name} MCP server tools. {info.description.rstrip('.')}. "
        f"Use when the user asks for anything the {info.name} tools cover."
    )
    content = f"""---
name: {info.plugin_name}
description: {json.dumps(description)}
---

# {info.name}

{info.description}

## Tools

These tools come from the `{info.name}` MCP server (in Claude Code they are prefixed
`mcp__...{info.plugin_name}__`).

{tool_lines}

## How to use

1. Pick the tool whose description matches the request; prefer read-only tools first.
2. Pass arguments exactly as the tool's input schema describes.
3. If a tool asks the user for input (elicitation), wait for their answer rather than guessing.
4. Summarise tool results for the user; don't dump raw JSON unless asked.

<!-- Generated by mcp-forge. Edit freely: describe workflows, gotchas, and examples here. -->
"""
    created: List[Path] = []
    _write_new(project_dir / "skills" / info.plugin_name / "SKILL.md", content, created)
    return created


def write_plugin(project_dir: Path) -> List[Path]:
    """Write a Claude Code plugin manifest and a single-plugin marketplace."""
    info = read_project_info(project_dir)
    plugin = {
        "name": info.plugin_name,
        "version": info.version,
        "description": info.description,
        "author": {"name": info.author},
        "keywords": ["mcp"],
        "mcpServers": {
            info.plugin_name: {
                "command": "uv",
                "args": ["run", "--directory", "${CLAUDE_PLUGIN_ROOT}", "python", "server.py"],
            }
        },
    }
    if info.github_user:
        plugin["repository"] = f"https://github.com/{info.github_user}/{info.name}"
    marketplace = {
        "name": info.plugin_name,
        "owner": {"name": info.author},
        "description": f"Claude Code plugin for the {info.name} MCP server",
        "plugins": [
            {
                "name": info.plugin_name,
                "source": "./",
                "description": info.description,
            }
        ],
    }
    created: List[Path] = []
    _write_new(project_dir / ".claude-plugin" / "plugin.json", _json(plugin), created)
    _write_new(project_dir / ".claude-plugin" / "marketplace.json", _json(marketplace), created)
    return created


def write_mcpb(project_dir: Path) -> List[Path]:
    """Write an MCP Bundle manifest (uv server type) and .mcpbignore."""
    info = read_project_info(project_dir)
    manifest = {
        "manifest_version": MCPB_MANIFEST_VERSION,
        "name": info.plugin_name,
        "display_name": info.name,
        "version": info.version,
        "description": info.description,
        "author": {"name": info.author},
        "server": {
            "type": "uv",
            "entry_point": "server.py",
            "mcp_config": {
                "command": "uv",
                "args": ["run", "--directory", "${__dirname}", "python", "server.py"],
            },
        },
        "tools": [
            {"name": tool.name, "description": tool.description} for tool in read_tools(project_dir)
        ],
        "compatibility": {"platforms": ["darwin", "linux", "win32"]},
    }
    ignore = (
        ".venv/\n__pycache__/\n.pytest_cache/\ntests/\n.env\n*.mcpb\n"
        ".claude-plugin/\nskills/\nDockerfile\n.dockerignore\nserver.json\n"
    )
    created: List[Path] = []
    _write_new(project_dir / "manifest.json", _json(manifest), created)
    _write_new(project_dir / ".mcpbignore", ignore, created)
    return created


def write_registry(project_dir: Path) -> List[Path]:
    """Write server.json for the MCP Registry and add the PyPI ownership marker to README.md."""
    info = read_project_info(project_dir)
    owner = info.github_user or "your-github-username"
    registry_name = f"io.github.{owner}/{info.name}"
    server = {
        "$schema": REGISTRY_SCHEMA,
        "name": registry_name,
        "title": info.name,
        "description": info.description[:100],
        "version": info.version,
        "packages": [
            {
                "registryType": "pypi",
                "registryBaseUrl": "https://pypi.org",
                "identifier": info.name,
                "version": info.version,
                "runtimeHint": "uvx",
                "transport": {"type": "stdio"},
            }
        ],
    }
    if info.github_user:
        server["repository"] = {"url": f"https://github.com/{owner}/{info.name}", "source": "github"}

    created: List[Path] = []
    _write_new(project_dir / "server.json", _json(server), created)

    # The registry verifies PyPI ownership via this marker in the package README
    readme = project_dir / "README.md"
    marker = f"<!-- mcp-name: {registry_name} -->"
    if readme.exists() and "mcp-name:" not in readme.read_text():
        readme.write_text(readme.read_text().rstrip("\n") + f"\n\n{marker}\n")
    return created


def write_docker(project_dir: Path) -> List[Path]:
    """Write a Dockerfile (uv-based) that serves the server over Streamable HTTP."""
    dockerfile = """FROM ghcr.io/astral-sh/uv:python3.12-bookworm-slim

WORKDIR /app
ENV UV_COMPILE_BYTECODE=1

# Install dependencies first so they are cached between code changes
COPY pyproject.toml ./
RUN uv pip install --system --no-cache -r pyproject.toml
COPY . .

# Listen on all interfaces inside the container. With auth, set MCP_PUBLIC_URL
# to the URL clients use (e.g. https://mcp.example.com).
ENV MCP_HOST=0.0.0.0 MCP_PORT=8000
EXPOSE 8000
HEALTHCHECK CMD python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/health')"

USER nobody
CMD ["python", "server.py", "--http"]
"""
    ignore = ".venv/\n__pycache__/\n*.py[cod]\n.pytest_cache/\n.env\n.git/\n*.mcpb\n"
    created: List[Path] = []
    _write_new(project_dir / "Dockerfile", dockerfile, created)
    _write_new(project_dir / ".dockerignore", ignore, created)
    return created
